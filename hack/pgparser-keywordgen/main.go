// Command keywordgen writes the keyword tables the scanner and the identifier quoting rules use,
// from the keyword lists in the grammar file. Run it through make generate-pgparser.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"
)

const (
	generatedBy  = "// Code generated by keywordgen from sql.y. DO NOT EDIT.\n\n"
	filePerm     = 0o644
	wantArgCount = 4
)

var (
	// keyword list rules, by whether an identifier of that spelling must be quoted: every keyword
	// that is not unreserved is, so that a column named for a type or a function reads back
	reservedRules = []string{
		"reserved_keyword", "extra_reserved_keyword", "col_name_keyword",
		"type_func_name_no_extra_keyword", "type_func_name_extra_keyword",
	}
	otherRules   = []string{"unreserved_keyword"}
	tokenPattern = regexp.MustCompile(`[A-Z][A-Z0-9_]*`)
)

func keywords(grammar, rule string) []string {
	_, body, found := strings.Cut(grammar, "\n"+rule+":\n")
	if !found {
		fail(fmt.Errorf("the grammar has no %s rule", rule))
	}
	body, _, _ = strings.Cut(body, "\n\n")
	return tokenPattern.FindAllString(body, -1)
}

func fail(err error) {
	_, _ = fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func write(path string, src *bytes.Buffer) {
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(path, formatted, filePerm); err != nil { // #nosec G703 -- the developer names the paths
		fail(err)
	}
}

func main() {
	if len(os.Args) != wantArgCount {
		fail(errors.New("usage: keywordgen <sql.y> <keyword ids .go> <reserved keywords .go>"))
	}
	data, err := os.ReadFile(os.Args[1]) // #nosec G703 -- the developer names the paths
	if err != nil {
		fail(err)
	}
	grammar := string(data)
	var reserved, all []string
	for _, rule := range reservedRules {
		reserved = append(reserved, keywords(grammar, rule)...)
	}
	all = append(all, reserved...)
	for _, rule := range otherRules {
		all = append(all, keywords(grammar, rule)...)
	}
	slices.Sort(reserved)
	slices.Sort(all)
	all = slices.Compact(all)

	var ids bytes.Buffer
	ids.WriteString(generatedBy + "package pgparser\n\n")
	ids.WriteString("// keywordID returns the token of a lower-case keyword, or IDENT for any other word\n")
	ids.WriteString("func keywordID(word string) int32 {\n\tswitch word {\n")
	for _, token := range all {
		fmt.Fprintf(&ids, "\tcase %q:\n\t\treturn %s\n", strings.ToLower(token), token)
	}
	ids.WriteString("\t}\n\treturn IDENT\n}\n")
	write(os.Args[2], &ids)

	var res bytes.Buffer
	res.WriteString(generatedBy + "package lex\n\n")
	res.WriteString("// reservedKeyword reports whether a lower-case word is a reserved keyword of the grammar\n")
	res.WriteString("func reservedKeyword(word string) bool {\n\tswitch word {\n\tcase ")
	for i, token := range reserved {
		if i > 0 {
			res.WriteString(",\n\t\t")
		}
		fmt.Fprintf(&res, "%q", strings.ToLower(token))
	}
	res.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n")
	write(os.Args[3], &res)
}

package pgparser

import (
	"fmt"
	"strings"

	"github.com/trickstercache/trickster/v2/pkg/parsing/pgparser/ast"
)

type lexer struct {
	in string
	// tokens contains tokens generated by the scanner.
	tokens []sqlSymType

	// The type that should be used when an INT or SERIAL is encountered.
	nakedIntType *ast.T

	// lastPos is the position into the tokens slice of the last
	// token returned by Lex().
	lastPos int

	stmt *ast.Select

	lastError error
}

func (l *lexer) init(sql string, tokens []sqlSymType, nakedIntType *ast.T) {
	l.in = sql
	l.tokens = tokens
	l.lastPos = -1
	l.stmt = nil
	l.lastError = nil

	l.nakedIntType = nakedIntType
}

// cleanup is used to avoid holding on to memory unnecessarily (for the cases
// where we reuse a parser).
func (l *lexer) cleanup() {
	l.tokens = nil
	l.stmt = nil
	l.lastError = nil
}

// Lex lexes a token from input.
func (l *lexer) Lex(lval *sqlSymType) int {
	l.lastPos++
	// The core lexing takes place in the scanner. Here we do a small bit of post
	// processing of the lexical tokens so that the grammar only requires
	// one-token lookahead despite SQL requiring multi-token lookahead in some
	// cases. These special cases are handled below and the returned tokens are
	// adjusted to reflect the lookahead (LA) that occurred.
	if l.lastPos >= len(l.tokens) {
		lval.id = 0
		lval.pos = int32(len(l.in)) // #nosec G115 -- ParseQuery rejects statements of 2 GiB or more
		lval.str = tokenEOF
		return 0
	}
	*lval = l.tokens[l.lastPos]

	var nextID int32
	if l.lastPos+1 < len(l.tokens) {
		nextID = l.tokens[l.lastPos+1].id
	}
	switch lval.id {
	case NOT:
		switch nextID {
		case BETWEEN, IN, LIKE, ILIKE, SIMILAR:
			lval.id = NOT_LA
		}
	case WITH:
		switch nextID {
		case TIME, ORDINALITY:
			lval.id = WITH_LA
		}
	case NULLS:
		switch nextID {
		case FIRST, LAST:
			lval.id = NULLS_LA
		}
	}

	return int(lval.id)
}

func (l *lexer) lastToken() sqlSymType {
	if l.lastPos < 0 {
		return sqlSymType{}
	}

	if l.lastPos >= len(l.tokens) {
		return sqlSymType{
			id:  0,
			pos: int32(len(l.in)), // #nosec G115 -- as above
			str: tokenEOF,
		}
	}
	return l.tokens[l.lastPos]
}

// writtenText returns the statement text from start through the last token the parser consumed,
// which is the one before a lookahead token the parser has read but not shifted
func (l *lexer) writtenText(start int32, lookahead bool) string {
	last := l.lastPos
	if lookahead {
		last--
	}
	if last < 0 || last >= len(l.tokens) || l.tokens[last].end < start || start < 0 {
		return ""
	}
	return l.in[start:l.tokens[last].end]
}

// tokenText returns a token's text as the statement wrote it
func (l *lexer) tokenText(start, end int32) string {
	if start < 0 || end < start || int(end) > len(l.in) {
		return ""
	}
	return l.in[start:end]
}

// textBefore returns the statement text from start up to the token at next, without trailing space
func (l *lexer) textBefore(start, next int32) string {
	if start < 0 || next < start || int(next) > len(l.in) {
		return ""
	}
	return strings.TrimRight(l.in[start:next], spaceChars)
}

// SetStmt is called from the parser when the statement is constructed.
func (l *lexer) SetStmt(stmt *ast.Select) {
	l.stmt = stmt
}

// Unimplemented wraps up an error for syntax the grammar recognizes and does not support.
func (l *lexer) Unimplemented(feature string) {
	l.syntaxError(fmt.Sprintf(unimplementedFormat, feature))
}

func (l *lexer) setErr(err error) {
	l.syntaxError(err.Error())
}

func (l *lexer) Error(e string) {
	l.syntaxError(e)
}

// syntaxError records an error at the last token the parser read.
func (l *lexer) syntaxError(message string) {
	lastTok := l.lastToken()
	l.lastError = &SyntaxError{
		Message: message, Near: lastTok.str, Pos: int(lastTok.pos), Lexical: lastTok.id == ERROR,
	}
}
